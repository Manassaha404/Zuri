"use client";

import { useState, useEffect } from "react";
import {
  ChatHeader,
  ChatInterface,
  formatConversationsToGroups,
  initialConnectors,
  Sidebar,
  type ChatGroup,
  type Connector,
  type PinnedMessage,
  type User,
} from "@/components/chat";
import { useUIStore, useInitUIStore } from "@/store/uiStore";
import { useUserInfoStore } from "@/store/userInfoStore";
import { useAgentStore } from "@/store/agentStore";
import { useConversations } from "@/hook/agent";

export default function DashboardPage() {
  useInitUIStore();
  const { darkMode } = useUIStore();
  const { fullName, username, email: userEmail } = useUserInfoStore();
  const { conversations, isLoading: isConversationsLoading } =
    useConversations();
  const isAgentThinking = useAgentStore((state) => state.status === "running");
  const agentTitle = useAgentStore((state) => state.title);
  const isTitleUpdating = useAgentStore((state) => state.isTitleUpdating);
  const [reloadKey, setReloadKey] = useState(0);
  const [activeSessionId, setActiveSessionId] = useState(() =>
    crypto.randomUUID(),
  );

  const [selectedChat, setSelectedChat] = useState("New chat");

  const [chatGroups, setChatGroups] = useState<ChatGroup[]>([]);

  const [connectors, setConnectors] = useState<Connector[]>(initialConnectors);

  const [pinnedMessages, setPinnedMessages] = useState<PinnedMessage[]>([]);

  const [memory, setMemory] = useState("");

  const user: User = {
    name: fullName?.trim() || username?.trim() || "alex",
    email: userEmail?.trim() || "alex@zuri.chat",
  };

  // Always reset agent store to clean state on initial page load
  useEffect(() => {
    useAgentStore.getState().reset();
  }, []);

  // Sync conversation groups with backend conversations
  useEffect(() => {
    if (conversations && conversations.length > 0) {
      const formatted = formatConversationsToGroups(conversations);
      setChatGroups(formatted);
    }
  }, [conversations]);

  // Sync real-time title generated by the agent
  useEffect(() => {
    if (agentTitle && agentTitle.trim() && agentTitle !== selectedChat) {
      const prevTitle = selectedChat;
      setSelectedChat(agentTitle);
      setChatGroups((prev) =>
        prev.map((group) => ({
          ...group,
          items: group.items.map((item) => {
            const itemTitle = typeof item === "string" ? item : item.title;
            if (itemTitle === prevTitle || itemTitle.startsWith("New chat")) {
              return typeof item === "string"
                ? agentTitle
                : { ...item, title: agentTitle };
            }
            return item;
          }),
        })),
      );
    }
  }, [agentTitle, selectedChat]);

  function newChat() {
    useAgentStore.getState().reset();
    setActiveSessionId(crypto.randomUUID());
    setSelectedChat("New chat");
  }

  function selectChat(title: string, conversationId?: string) {
    if (
      title === selectedChat &&
      (!conversationId ||
        conversationId === useAgentStore.getState().conversationId)
    ) {
      return;
    }
    useAgentStore.getState().reset();
    if (conversationId) {
      useAgentStore.getState().setConversationId(conversationId);
    }
    useAgentStore.getState().setTitle(title);
    setActiveSessionId(conversationId ?? crypto.randomUUID());
    setSelectedChat(title);
  }

  function handleReload() {
    setReloadKey((k) => k + 1);
  }

  function pinMessage(title: string) {
    const cleanTitle = title.trim();
    if (!cleanTitle) return;

    setPinnedMessages((prev) => [
      { id: Date.now(), title: cleanTitle },
      ...prev.filter((item) => item.title !== cleanTitle),
    ]);
  }

  const themeClass = darkMode ? "D dark" : "L";

  return (
    <div className={`app ${themeClass}`}>
      <Sidebar
        user={user}
        onNewChat={newChat}
        onSelectChat={selectChat}
        selectedChat={selectedChat}
        chatGroups={chatGroups}
        setChatGroups={setChatGroups}
        connectors={connectors}
        setConnectors={setConnectors}
        pinnedMessages={pinnedMessages}
        setPinnedMessages={setPinnedMessages}
        memory={memory}
        setMemory={setMemory}
        isLoadingConversations={isConversationsLoading}
      />

      <div className="flex-1 flex flex-col h-full min-h-0 min-w-0 overflow-hidden">
        {/* Top Header with animated chat topic on the left and reload button on the right */}
        <ChatHeader
          selectedChat={selectedChat}
          isTitleUpdating={isTitleUpdating}
          darkMode={darkMode}
          loading={isAgentThinking}
          onReload={handleReload}
          onNewChat={newChat}
          className="pt-3.5 pb-2.5 sm:pt-4 sm:pb-3"
        />

        {/* Main chat interface */}
        <ChatInterface
          key={`${activeSessionId}-${reloadKey}`}
          selectedChat={selectedChat}
          darkMode={darkMode}
          onPinMessage={pinMessage}
          userName={user.name}
        />
      </div>
    </div>
  );
}
