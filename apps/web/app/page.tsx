"use client";

import { useState, useEffect, useMemo } from "react";
import {
  ChatHeader,
  ChatInterface,
  formatConversationsToGroups,
  initialConnectors,
  Sidebar,
  type ChatGroup,
  type Connector,
  type PinnedMessage,
  type User,
} from "@/components/chat";
import { useUIStore, useInitUIStore } from "@/store/uiStore";
import { useUserInfoStore } from "@/store/userInfoStore";
import { useAgentStore } from "@/store/agentStore";
import {
  useConversations,
  usePinConversation,
  useUpdateConversationTitle,
  useDeleteConversation,
} from "@/hook/agent";

export default function DashboardPage() {
  useInitUIStore();
  const { darkMode } = useUIStore();
  const { fullName, username, email: userEmail } = useUserInfoStore();
  const {
    conversations,
    pinnedConversations,
    isLoading: isConversationsLoading,
  } = useConversations();
  const { togglePin } = usePinConversation();
  const { updateTitle } = useUpdateConversationTitle();
  const { deleteConversation } = useDeleteConversation();
  const isAgentThinking = useAgentStore((state) => state.status === "running");
  const agentTitle = useAgentStore((state) => state.title);
  const isTitleUpdating = useAgentStore((state) => state.isTitleUpdating);
  const currentConversationId = useAgentStore((state) => state.conversationId);
  const [reloadKey, setReloadKey] = useState(0);
  const [activeSessionId, setActiveSessionId] = useState(() =>
    crypto.randomUUID(),
  );

  const [selectedChat, setSelectedChat] = useState("New chat");

  const [chatGroups, setChatGroups] = useState<ChatGroup[]>([]);

  const [connectors, setConnectors] = useState<Connector[]>(initialConnectors);

  const [pinnedMessages, setPinnedMessages] = useState<PinnedMessage[]>([]);

  const [memory, setMemory] = useState("");

  const user: User = {
    name: fullName?.trim() || username?.trim() || "alex",
    email: userEmail?.trim() || "alex@zuri.chat",
  };

  const currentConversation = useMemo(
    () => conversations.find((c) => c.conversationId === currentConversationId),
    [conversations, currentConversationId],
  );
  const isCurrentChatPinned = Boolean(currentConversation?.isPinned);

  // Always reset agent store to clean state on initial page load
  useEffect(() => {
    useAgentStore.getState().reset();
  }, []);

  // Sync conversation groups with backend conversations (unpinned conversations grouped chronologically)
  useEffect(() => {
    if (conversations && conversations.length > 0) {
      const unpinned = conversations.filter((c) => !c.isPinned);
      const formatted = formatConversationsToGroups(unpinned);
      setChatGroups(formatted);
    } else {
      setChatGroups((prev) => (prev.length === 0 ? prev : []));
    }
  }, [conversations]);

  // Sync real-time title generated by the agent
  useEffect(() => {
    if (agentTitle && agentTitle.trim() && agentTitle !== selectedChat) {
      const prevTitle = selectedChat;
      setSelectedChat(agentTitle);
      setChatGroups((prev) =>
        prev.map((group) => ({
          ...group,
          items: group.items.map((item) => {
            const itemTitle = typeof item === "string" ? item : item.title;
            if (itemTitle === prevTitle || itemTitle.startsWith("New chat")) {
              return typeof item === "string"
                ? agentTitle
                : { ...item, title: agentTitle };
            }
            return item;
          }),
        })),
      );
    }
  }, [agentTitle, selectedChat]);

  function newChat() {
    useAgentStore.getState().reset();
    setActiveSessionId(crypto.randomUUID());
    setSelectedChat("New chat");
  }

  function selectChat(title: string, conversationId?: string) {
    if (
      title === selectedChat &&
      (!conversationId ||
        conversationId === useAgentStore.getState().conversationId)
    ) {
      return;
    }
    useAgentStore.getState().reset();
    if (conversationId) {
      useAgentStore.getState().setConversationId(conversationId);
    }
    useAgentStore.getState().setTitle(title);
    setActiveSessionId(conversationId ?? crypto.randomUUID());
    setSelectedChat(title);
  }

  function handleReload() {
    setReloadKey((k) => k + 1);
  }

  const handleTogglePin = async (
    conversationId: string,
    targetPinned?: boolean,
  ) => {
    try {
      await togglePin(conversationId, targetPinned);
    } catch (err) {
      console.error("Failed to toggle pin on conversation:", err);
    }
  };

  const handleRenameConversation = async (
    conversationId: string,
    newTitle: string,
  ) => {
    try {
      await updateTitle(conversationId, newTitle);
      if (conversationId === currentConversationId) {
        setSelectedChat(newTitle);
      }
    } catch (err) {
      console.error("Failed to rename conversation:", err);
    }
  };

  const handleDeleteConversation = async (conversationId: string) => {
    try {
      await deleteConversation(conversationId);
      if (conversationId === currentConversationId) {
        newChat();
      }
    } catch (err) {
      console.error("Failed to delete conversation:", err);
    }
  };

  function pinMessage(title: string) {
    if (currentConversationId) {
      void handleTogglePin(currentConversationId, true);
    }
  }

  const themeClass = darkMode ? "D dark" : "L";

  return (
    <div className={`app ${themeClass}`}>
      <Sidebar
        user={user}
        onNewChat={newChat}
        onSelectChat={selectChat}
        selectedChat={selectedChat}
        chatGroups={chatGroups}
        setChatGroups={setChatGroups}
        connectors={connectors}
        setConnectors={setConnectors}
        pinnedMessages={pinnedMessages}
        setPinnedMessages={setPinnedMessages}
        pinnedConversations={pinnedConversations}
        onTogglePin={handleTogglePin}
        onRenameConversation={handleRenameConversation}
        onDeleteConversation={handleDeleteConversation}
        memory={memory}
        setMemory={setMemory}
        isLoadingConversations={isConversationsLoading}
      />

      <div className="flex-1 flex flex-col h-full min-h-0 min-w-0 overflow-hidden">
        {/* Top Header with animated chat topic on the left and reload button on the right */}
        <ChatHeader
          selectedChat={selectedChat}
          isTitleUpdating={isTitleUpdating}
          darkMode={darkMode}
          loading={isAgentThinking}
          onReload={handleReload}
          onNewChat={newChat}
          isPinned={isCurrentChatPinned}
          canPin={Boolean(currentConversationId)}
          canManage={Boolean(currentConversationId)}
          onTogglePin={() => {
            if (currentConversationId) {
              void handleTogglePin(currentConversationId, !isCurrentChatPinned);
            }
          }}
          onRename={(newTitle) => {
            if (currentConversationId) {
              void handleRenameConversation(currentConversationId, newTitle);
            }
          }}
          onDelete={() => {
            if (currentConversationId) {
              void handleDeleteConversation(currentConversationId);
            }
          }}
          className="pt-3.5 pb-2.5 sm:pt-4 sm:pb-3"
        />

        {/* Main chat interface */}
        <ChatInterface
          key={`${activeSessionId}-${reloadKey}`}
          selectedChat={selectedChat}
          darkMode={darkMode}
          onPinMessage={pinMessage}
          userName={user.name}
        />
      </div>
    </div>
  );
}
